CREATE TABLE st_shift_icmal (
  account_id CHAR(36) NOT NULL PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (account_id) REFERENCES st_accounts(id)
) ENGINE=InnoDB;
CREATE TABLE st_shift_special_operations (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  station_id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  kind ENUM('TTS','GIFT_LOAD','GIFT_USE','PARTNER','TEST_OUT','TEST_RETURN','TANKER_IN') NOT NULL,
  model ENUM('DRAFT','EXISTING_PAYMENT','RECEIVABLE','PREPAID','PHYSICAL') NOT NULL DEFAULT 'DRAFT',
  status ENUM('DRAFT','RECORDED','VOID') NOT NULL DEFAULT 'DRAFT',
  source VARCHAR(190) NOT NULL,
  provider VARCHAR(190) NOT NULL,
  reference VARCHAR(190) NOT NULL,
  plate VARCHAR(32) NULL,
  customer VARCHAR(190) NULL,
  instrument VARCHAR(64) NULL,
  amount_minor BIGINT NOT NULL DEFAULT 0,
  volume_ml BIGINT NOT NULL DEFAULT 0,
  document_ml BIGINT NULL,
  nozzle_id CHAR(36) NULL,
  tank_id CHAR(36) NULL,
  start_meter_ml BIGINT NULL,
  end_meter_ml BIGINT NULL,
  related_id CHAR(36) NULL,
  payment_id CHAR(36) NULL,
  slip_id CHAR(36) NULL,
  settlement ENUM('DRAFT','PENDING','SETTLED','NOT_APPLICABLE') NOT NULL DEFAULT 'DRAFT',
  settlement_method ENUM('DRAFT','CASH','BANK','PROVIDER') NOT NULL DEFAULT 'DRAFT',
  note VARCHAR(1000) NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  reviewer_id INT NULL,
  created_by INT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_special_reference (station_id,kind,provider,reference),
  UNIQUE KEY uq_special_payment (payment_id),
  UNIQUE KEY uq_special_slip (slip_id),
  KEY ix_special_account (account_id,status),
  KEY ix_special_wallet (station_id,provider,instrument,status),
  FOREIGN KEY (tenant_id) REFERENCES st_tenants(id),
  FOREIGN KEY (station_id) REFERENCES st_stations(id),
  FOREIGN KEY (account_id) REFERENCES st_accounts(id),
  FOREIGN KEY (nozzle_id) REFERENCES st_fuel_nozzles(id),
  FOREIGN KEY (tank_id) REFERENCES st_fuel_tanks(id),
  FOREIGN KEY (related_id) REFERENCES st_shift_special_operations(id),
  FOREIGN KEY (payment_id) REFERENCES st_payments(id),
  FOREIGN KEY (slip_id) REFERENCES st_slips(id),
  FOREIGN KEY (reviewer_id) REFERENCES users(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE st_shift_tank_checks (
  account_id CHAR(36) NOT NULL,
  tank_id CHAR(36) NOT NULL,
  opening_ml BIGINT NOT NULL,
  closing_ml BIGINT NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  PRIMARY KEY (account_id,tank_id),
  FOREIGN KEY (account_id) REFERENCES st_accounts(id),
  FOREIGN KEY (tank_id) REFERENCES st_fuel_tanks(id)
) ENGINE=InnoDB;
