CREATE TABLE st_pos_slip_drafts (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  station_id CHAR(36) NOT NULL,
  shift_id CHAR(36) NOT NULL,
  account_id CHAR(36) NOT NULL,
  staff_user_id INT NOT NULL,
  source_sha256 CHAR(64) NOT NULL,
  transaction_key CHAR(64) NULL,
  mime_type ENUM('image/jpeg','image/png') NOT NULL,
  byte_size INT UNSIGNED NOT NULL,
  image_bytes MEDIUMBLOB NOT NULL,
  ocr_provider ENUM('LOCAL','GEMINI','MANUAL') NOT NULL DEFAULT 'MANUAL',
  ocr_json LONGTEXT NULL,
  values_json LONGTEXT NULL,
  review_status ENUM('DRAFT','PAYMENT_CREATED','NON_SALE_REVIEWED','REJECTED') NOT NULL DEFAULT 'DRAFT',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  confirmed_slip_id CHAR(36) NULL,
  confirmed_by INT NULL,
  confirmed_at DATETIME(3) NULL,
  created_by INT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_pos_slip_source (station_id,source_sha256),
  UNIQUE KEY uq_pos_slip_transaction (station_id,transaction_key),
  UNIQUE KEY uq_pos_slip_payment (confirmed_slip_id),
  KEY ix_pos_slip_staff_review (tenant_id,station_id,staff_user_id,review_status,created_at),
  KEY ix_pos_slip_account (account_id,created_at),
  CONSTRAINT fk_pos_slip_tenant FOREIGN KEY (tenant_id) REFERENCES st_tenants(id),
  CONSTRAINT fk_pos_slip_station FOREIGN KEY (station_id) REFERENCES st_stations(id),
  CONSTRAINT fk_pos_slip_shift FOREIGN KEY (shift_id) REFERENCES st_shifts(id),
  CONSTRAINT fk_pos_slip_account FOREIGN KEY (account_id) REFERENCES st_accounts(id),
  CONSTRAINT fk_pos_slip_staff FOREIGN KEY (staff_user_id) REFERENCES users(id),
  CONSTRAINT fk_pos_slip_payment FOREIGN KEY (confirmed_slip_id) REFERENCES st_slips(id),
  CONSTRAINT fk_pos_slip_confirmed_by FOREIGN KEY (confirmed_by) REFERENCES users(id),
  CONSTRAINT fk_pos_slip_created_by FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB;
