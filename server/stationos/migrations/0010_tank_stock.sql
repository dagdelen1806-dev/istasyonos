CREATE TABLE st_tank_cards (
  tank_id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  station_id CHAR(36) NOT NULL,
  tank_number VARCHAR(64) NOT NULL,
  capacity_ml BIGINT NOT NULL,
  critical_ml BIGINT NOT NULL,
  tolerance_ml BIGINT NOT NULL,
  stock_ml BIGINT NULL,
  initialized_at DATETIME(3) NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY uq_tank_number (station_id,tank_number),
  FOREIGN KEY (tank_id) REFERENCES st_fuel_tanks(id),
  FOREIGN KEY (tenant_id) REFERENCES st_tenants(id),
  FOREIGN KEY (station_id) REFERENCES st_stations(id)
) ENGINE=InnoDB;
CREATE TABLE st_tank_requests (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  station_id CHAR(36) NOT NULL,
  tank_id CHAR(36) NOT NULL,
  kind ENUM('OPENING','DELIVERY','ADJUSTMENT') NOT NULL,
  status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
  target_ml BIGINT NULL,
  document_ml BIGINT NULL,
  measured_ml BIGINT NULL,
  supplier_id CHAR(36) NULL,
  reference VARCHAR(190) NOT NULL,
  note VARCHAR(1000) NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  expected_revision INT UNSIGNED NOT NULL,
  created_by INT NOT NULL,
  reviewer_id INT NULL,
  review_note VARCHAR(1000) NULL,
  review_evidence VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_tank_delivery (tank_id,kind,supplier_id,reference),
  KEY ix_tank_pending (station_id,status),
  FOREIGN KEY (tenant_id) REFERENCES st_tenants(id),
  FOREIGN KEY (station_id) REFERENCES st_stations(id),
  FOREIGN KEY (tank_id) REFERENCES st_tank_cards(tank_id),
  FOREIGN KEY (supplier_id) REFERENCES st_suppliers(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (reviewer_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE st_tank_delivery_links (
  request_id CHAR(36) NOT NULL PRIMARY KEY,
  operation_id CHAR(36) NOT NULL UNIQUE,
  linked_by INT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (request_id) REFERENCES st_tank_requests(id),
  FOREIGN KEY (operation_id) REFERENCES st_shift_special_operations(id),
  FOREIGN KEY (linked_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE st_tank_ledger (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tank_id CHAR(36) NOT NULL,
  kind ENUM('OPENING','SALE','TEST_OUT','TEST_RETURN','DELIVERY','ADJUSTMENT') NOT NULL,
  delta_ml BIGINT NOT NULL,
  before_ml BIGINT NOT NULL,
  after_ml BIGINT NOT NULL,
  source_key VARCHAR(100) NOT NULL,
  account_id CHAR(36) NULL,
  request_id CHAR(36) NULL,
  reference VARCHAR(190) NOT NULL,
  note VARCHAR(1000) NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  actor_id INT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_tank_source (tank_id,source_key),
  KEY ix_tank_ledger_date (tank_id,created_at),
  FOREIGN KEY (tank_id) REFERENCES st_tank_cards(tank_id),
  FOREIGN KEY (account_id) REFERENCES st_accounts(id),
  FOREIGN KEY (request_id) REFERENCES st_tank_requests(id),
  FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE st_tank_measurements (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tank_id CHAR(36) NOT NULL,
  measured_ml BIGINT NOT NULL,
  theoretical_ml BIGINT NULL,
  difference_ml BIGINT NULL,
  within_tolerance BOOLEAN NULL,
  revision INT UNSIGNED NOT NULL,
  note VARCHAR(1000) NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  actor_id INT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY ix_tank_measurement_date (tank_id,created_at),
  FOREIGN KEY (tank_id) REFERENCES st_tank_cards(tank_id),
  FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB;
