CREATE TABLE st_pos_carts (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  station_id CHAR(36) NOT NULL,
  session_id CHAR(36) NOT NULL,
  owner_user_id INT NOT NULL,
  device_id CHAR(36) NOT NULL,
  active_device_id CHAR(36) NULL,
  status ENUM('ACTIVE','HELD','CHECKED_OUT','CANCELLED') NOT NULL,
  version INT NOT NULL DEFAULT 1,
  label VARCHAR(100) NULL,
  lines_json JSON NOT NULL,
  sale_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_pos_active_cart (station_id,owner_user_id,active_device_id),
  KEY ix_pos_held_carts (tenant_id,station_id,status,updated_at),
  CONSTRAINT ck_pos_active_cart CHECK ((status='ACTIVE' AND active_device_id IS NOT NULL AND active_device_id=device_id) OR (status<>'ACTIVE' AND active_device_id IS NULL)),
  FOREIGN KEY (tenant_id) REFERENCES st_tenants(id),
  FOREIGN KEY (station_id) REFERENCES st_stations(id),
  FOREIGN KEY (session_id) REFERENCES st_pos_sessions(id),
  FOREIGN KEY (owner_user_id) REFERENCES users(id),
  FOREIGN KEY (sale_id) REFERENCES st_pos_sales(id)
) ENGINE=InnoDB;

CREATE TABLE st_pos_cart_events (
  id CHAR(36) NOT NULL PRIMARY KEY,
  cart_id CHAR(36) NOT NULL,
  tenant_id CHAR(36) NOT NULL,
  station_id CHAR(36) NOT NULL,
  actor_user_id INT NOT NULL,
  device_id CHAR(36) NOT NULL,
  request_id CHAR(36) NOT NULL,
  action ENUM('ADD','REDUCE','CANCEL','HOLD','RESUME','REPRICE','CHECKOUT') NOT NULL,
  reason VARCHAR(500) NULL,
  before_lines_json JSON NOT NULL,
  after_lines_json JSON NOT NULL,
  cart_version INT NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_pos_cart_event_request (actor_user_id,request_id),
  KEY ix_pos_cart_audit (tenant_id,station_id,created_at),
  FOREIGN KEY (cart_id) REFERENCES st_pos_carts(id),
  FOREIGN KEY (actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
